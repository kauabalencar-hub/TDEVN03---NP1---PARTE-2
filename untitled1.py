class Aluno:
    def __init__(self, nome, nota1, nota2):
        self.nome = nome
        self.nota1 = float(nota1)
        self.nota2 = float(nota2)

    def calcular_media(self):
        return (self.nota1 + self.nota2) / 2

    def verificar_situacao(self):
        media = self.calcular_media()
        if media >= 7.0:
            return "Aprovado"
        else:
            return "Reprovado"

try:
    nome_input = input("Digite o nome do aluno: ")
    nota1_input = input("Digite a primeira nota: ").replace(',', '.')
    nota2_input = input("Digite a segunda nota: ").replace(',', '.')

    aluno = Aluno(nome_input, nota1_input, nota2_input)
    media_final = aluno.calcular_media()
    situacao_final = aluno.verificar_situacao()

    print("\n--- Resultado Final ---")
    print(f"Aluno: {aluno.nome}")
    print(f"Nota 1: {aluno.nota1:.1f}")
    print(f"Nota 2: {aluno.nota2:.1f}")
    print(f"Média: {media_final:.1f}")
    print(f"Situação: {situacao_final}")
except ValueError:
    print("\nErro: Certifique-se de digitar valores numéricos válidos para as notas.")